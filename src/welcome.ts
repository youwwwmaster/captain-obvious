import { Context } from 'grammy';
import { config } from './config';
import { STARS_EXTRA_PACK_CALLS, STARS_EXTRA_PACK_PRICE } from './payments';

const DAILY = config.dailyLimit;

const START_MESSAGE = [
  '👋 <b>Капитан Очевидность</b>',
  'Поясняю <b>текст</b> или <b>картинку</b> из сообщения простыми словами (нейросеть).',
  '',
  '<b>Как вызвать</b>',
  '1. Найди сообщение с текстом или фото.',
  '2. Нажми «Ответить» на это сообщение.',
  '3. В ответе напиши одну из фраз ниже — Капитан ответит на <i>исходное</i> сообщение.',
  '',
  '<b>На какие фразы реагирую</b>',
  '<code>капитан объясни</code> · <code>эй капитан</code> · <code>эй, капитан</code>',
  '<code>капитан поясни</code> · <code>капитан твой выход</code> · <code>капитан объясняй</code>',
  '',
  '<b>Лимит и баланс</b>',
  `Бесплатно до <b>${DAILY}</b> вызовов за скользящие 24 часа. Если лимит кончился — можно купить пакет за <b>${STARS_EXTRA_PACK_PRICE}</b> ⭐ (+<b>${STARS_EXTRA_PACK_CALLS}</b> вызовов без срока, тратятся после бесплатных).`,
  `Чтобы посмотреть остаток: напиши в чат <code>эй капитан лимит</code> (тоже обычным сообщением, можно с реплаем — не важно).`,
  '',
  '<b>В личных сообщениях</b>',
  'Так же: ответ на сообщение с текстом/фото + фраза-триггер (своё или пересланное тебе).',
  '',
  '<b>В группе</b>',
  'Добавь бота в чат через «Участники» → «Добавить участников». Логика та же: ответ на сообщение с текстом или фото + фраза-триггер.',
  'Бесплатный лимит и купленные вызовы считаются по <b>тому, кто написал</b> фразу (не по чату целиком).',
  '',
  '<b>Команды</b>',
  '/start — краткая справка',
  '/terms — условия использования',
  '/support — написать в поддержку',
].join('\n');

export async function handleStartCommand(ctx: Context): Promise<void> {
  await ctx.reply(START_MESSAGE, {
    parse_mode: 'HTML',
    link_preview_options: { is_disabled: true },
    reply_parameters: ctx.message ? { message_id: ctx.message.message_id } : undefined,
  });
}
